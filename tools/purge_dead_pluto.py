import json, os

ROOT = r"C:\Users\Dorp\Documents\deepseek-harness\default-workspace\repo"

DEAD_PLUTO_IDS = {
    "pluto_scifi_movies_fhd",
    "america_test_kitchen_hd",
    "jamie_oliver_channel_hd",
    "cnbc_intl_fhd",
    "pluto_history_docu_fhd",
    "pluto_animals_nature_fhd",
    "pluto_classic_movies_fhd",
    "transformers_tv_fhd",
    "hell_kitchen_247_fhd",
    "smithsonian_channel_selects_fhd",
    "pluto_science_fhd",
}

# 1. Update channels.json
ch_json_path = os.path.join(ROOT, "channels.json")
with open(ch_json_path, "r", encoding="utf-8") as f:
    channels = json.load(f)

before_count = len(channels)
channels = [ch for ch in channels if ch["id"] not in DEAD_PLUTO_IDS]
after_count = len(channels)
print(f"channels.json: filtered from {before_count} to {after_count} channels (removed {before_count - after_count})")

with open(ch_json_path, "w", encoding="utf-8") as f:
    json.dump(channels, f, ensure_ascii=False, indent=2)
    f.write("\n")

# 2. Update channels.js
ch_js_path = os.path.join(ROOT, "channels.js")
with open(ch_js_path, "w", encoding="utf-8") as f:
    f.write("// generated by tools\nwindow.CHANNELS_DATA = " + json.dumps(channels, ensure_ascii=False) + ";\n")
print(f"channels.js: updated with {len(channels)} channels")

# 3. Update epg.json
epg_path = os.path.join(ROOT, "epg.json")
if os.path.exists(epg_path):
    with open(epg_path, "r", encoding="utf-8") as f:
        epg_data = json.load(f)
    if "channels" in epg_data:
        for did in DEAD_PLUTO_IDS:
            if did in epg_data["channels"]:
                del epg_data["channels"][did]
    with open(epg_path, "w", encoding="utf-8") as f:
        json.dump(epg_data, f, ensure_ascii=False)
        f.write("\n")
    print(f"epg.json: removed dead Pluto channel schedules")

print("Done purging dead Pluto TV channels!")

